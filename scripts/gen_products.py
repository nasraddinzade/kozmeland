"""Generate src/data/products.ts from the product block in kozmeland-claude-code.md
and the image-source records in scripts/image-sources/*.json.

    python -I scripts/gen_products.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "kozmeland-claude-code.md"
OUT = ROOT / "src" / "data" / "products.ts"
SOURCES_DIR = ROOT / "scripts" / "image-sources"
IMG_DIR = ROOT / "public" / "products"


def parse_rows():
    text = SPEC.read_text(encoding="utf-8")
    block = text.split("## 4.")[1].split("```")[1]
    rows = []
    for line in block.strip().splitlines():
        parts = [p.strip() for p in line.split("|")]
        parts += [""] * (10 - len(parts))
        slug, brand, name, volume, price, old, cat, ptype, date, note = parts[:10]
        rows.append(
            {
                "slug": slug,
                "brand": brand,
                "name": name,
                "volume": None if volume in ("-", "") else volume,
                "price": price,
                "oldPrice": None if old in ("-", "") else old,
                "category": cat,
                "type": ptype,
                "priceAsOf": date,
                "note": note or None,
            }
        )
    return rows


def load_sources():
    found = {}
    for f in sorted(SOURCES_DIR.glob("*.json")):
        for entry in json.loads(f.read_text(encoding="utf-8")):
            found[entry["slug"]] = entry
    return found


def ts_str(v):
    return "null" if v is None else json.dumps(v, ensure_ascii=False)


def main():
    rows = parse_rows()
    sources = load_sources()
    lines = []
    for r in rows:
        src = sources.get(r["slug"])
        has_img = (IMG_DIR / f"{r['slug']}.webp").exists() and src is not None and src.get("status") == "ok"
        # Prices are kept as the exact strings from the posts; numeric values only for sorting/sums.
        lines.append(
            "  {"
            f" slug: {ts_str(r['slug'])}, brand: {ts_str(r['brand'])}, name: {ts_str(r['name'])},"
            f" volume: {ts_str(r['volume'])}, price: {ts_str(r['price'])}, oldPrice: {ts_str(r['oldPrice'])},"
            f" category: {ts_str(r['category'])}, type: {ts_str(r['type'])}, priceAsOf: {ts_str(r['priceAsOf'])},"
            f" note: {ts_str(r['note'])}, noImage: {'false' if has_img else 'true'} }},"
        )
    body = "\n".join(lines)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// Generated by scripts/gen_products.py from kozmeland-claude-code.md — do not edit by hand.\n"
        "// Prices are discount prices read from the shop's Instagram posts (3 Sep – 21 Oct 2026).\n"
        'import type { RawProduct } from "./types";\n\n'
        f"export const RAW_PRODUCTS: RawProduct[] = [\n{body}\n];\n",
        encoding="utf-8",
    )
    write_sources(rows, sources)
    ok = sum(1 for r in rows if (IMG_DIR / f"{r['slug']}.webp").exists())
    print(f"{len(rows)} products, {ok} with images")


def write_sources(rows, sources):
    """public/products/SOURCES.md — where every photo comes from."""
    out = ["# Product photo sources", "", "| slug | status | source | page | note |", "|---|---|---|---|---|"]
    for r in rows:
        s = sources.get(r["slug"], {})
        status = s.get("status", "noImage")
        img = s.get("imageUrl") or ""
        page = s.get("pageUrl") or ""
        note = (s.get("note") or "").replace("|", "/").replace("\n", " ")
        src = f"{s.get('sourceName', '')} ({s.get('sourceType', '')})" if s else ""
        page_cell = f"[page]({page})" if page else ""
        img_cell = f"[image]({img})" if img else ""
        out.append(f"| {r['slug']} | {status} | {src} {img_cell} | {page_cell} | {note} |")
    (IMG_DIR / "SOURCES.md").write_text("\n".join(out) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
